-- ============================================================
-- 156 — Delivery minorista (app de pedidos para el público)
-- ============================================================
-- El público pide desde /pedir SIN usuario: nunca toca las tablas
-- directo. Todo pasa por 4 funciones SECURITY DEFINER que validan
-- horario, mínimo, cantidades y recalculan los precios del lado del
-- servidor (el precio que manda el celular no se usa nunca).
--
-- Etapa 1 = solo Río Primero: sale de la central (Mitre 670), con la
-- lista MINORISTA de la central y sus ofertas. Mayoristas y carnicerías
-- no usan el delivery. Monte Cristo viene después (cada boca vende lo
-- suyo) — por eso la tabla ya lleva sucursal_id.
--
-- Circuito: nuevo → pesado (el local carga los kilos reales y avisa el
-- total por WhatsApp) → pagado (si es transferencia) → en_camino →
-- entregado. El cobro se registra en la Caja como una venta común
-- (descuenta stock y entra al arqueo); venta_id la linkea.
-- ============================================================

-- Productos que el local no quiere publicar en el delivery.
alter table public.precios add column if not exists delivery_oculto boolean not null default false;

create table if not exists public.pedidos_delivery (
  id              bigint generated by default as identity primary key,  -- es el N° de pedido que ve el cliente
  token           uuid not null unique default gen_random_uuid(),       -- link de seguimiento (secreto)
  sucursal_id     integer not null default 1,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  cliente_nombre  text not null,
  telefono        text not null,
  direccion       text not null,
  referencias     text,
  nota            text,
  forma_pago      text not null check (forma_pago in ('efectivo','transferencia')),
  -- [{producto_id, nombre, categoria, pesable, cantidad, precio, importe, nota, kg_real, importe_real}]
  items           jsonb not null,
  subtotal_aprox  numeric not null,
  envio           numeric not null default 0,
  total_aprox     numeric not null,
  subtotal_final  numeric,
  total_final     numeric,
  estado          text not null default 'nuevo'
                  check (estado in ('nuevo','pesado','pagado','en_camino','entregado','cancelado')),
  motivo_cancelacion text,
  pesado_at       timestamptz,
  transferencia_avisada_at timestamptz,   -- el cliente tocó "Ya transferí"
  pagado_at       timestamptz,
  en_camino_at    timestamptz,
  entregado_at    timestamptz,
  cancelado_at    timestamptz,
  venta_id        uuid references public.ventas_minoristas(id) on delete set null
);

create index if not exists pedidos_delivery_estado_idx on public.pedidos_delivery (sucursal_id, estado, created_at desc);
create index if not exists pedidos_delivery_tel_idx on public.pedidos_delivery (telefono, created_at desc);

alter table public.pedidos_delivery enable row level security;

drop policy if exists pedidos_delivery_admin on public.pedidos_delivery;
create policy pedidos_delivery_admin on public.pedidos_delivery
  for all using (is_admin()) with check (is_admin());

-- Cada boca ve sólo sus pedidos (hoy todos son de la central).
drop policy if exists pedidos_delivery_boca on public.pedidos_delivery;
create policy pedidos_delivery_boca on public.pedidos_delivery
  as restrictive for all
  using (sucursal_id = mi_sucursal()) with check (sucursal_id = mi_sucursal());

